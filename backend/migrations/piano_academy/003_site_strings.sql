-- WHAT THE APP SAYS TO A LEARNER
--
-- 002 made the tables; these are the words that go in them. Everything the
-- app itself says - the header and the navigation, the cards drawn when it
-- cannot run, the home page with the learning path, a lesson and its steps,
-- Sheet Practice, Songs, the Note Trainer, Stats - is a key here, with its
-- English and its Slovak string. The owner's two pages (Translations,
-- Languages) have none: they stay English, written in their templates.
--
-- What is not a word of the app is not here, and stands in a string only as
-- a {placeholder} or as it is: note names (the English letters C D E F G A B,
-- in Slovak too - B, never H), chord letters, "BPM", song titles, MIDI device
-- names, "Piano Academy", "anotoki", "MIDI", "Chrome", "Edge". Neither are
-- the entries of the list of changes (public/changelog.json).
--
-- The code names a key and the page shows its string; a key with no row
-- shows as the key itself, so the list below and the frontend are held
-- together by a test (tests/unit/translations.test.php): every key the
-- frontend asks for is here, and every key here is asked for. The keys
-- under path. are put together at run time from the path's own ids
-- (frontend: core/i18n/dynamic-keys.ts). The English of what is drawn
-- while the app has no strings at all - the shell and its cards - is also
-- kept in the frontend (core/i18n/kept-english.ts), letter for letter what
-- is written here; the same test holds the two equal.
--
-- The description is all a translator has: where the string is shown and
-- what its {placeholders} stand for. The English string fixes which
-- placeholders a key has - the code fills exactly those - so English may be
-- reworded on the Translations page but never gain or lose one, and another
-- language may use only those.
--
-- Keys ending in .one, .few and .other are the forms of one plural, asked for
-- by the family's name with a number: Slovak says "1 nota", "3 noty",
-- "12 nôt". English never picks .few; it says there what .other says,
-- because it is what a language with no string of its own falls back to.
-- Slovak speaks to the learner informally here (ty), and says nothing that
-- would have to know whether the learner is a he or a she.
--
-- Every insert steps aside for a row that is already there: a string
-- reworded on the Translations page is the owner's and is never written
-- over. So a string added or reworded after this is a migration of its own,
-- never an edit of this file.
--
-- One string on a line, an apostrophe written twice and nothing else
-- escaped: that is all the statement splitter (api/migration_runner.php)
-- knows of a string.
